defmodule AlplusWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :alplus

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  #
  # Session policy (ARCHITECTURE.md §10): 30-day absolute lifetime,
  # `__Host-` prefixed cookie, HttpOnly, Secure, SameSite=Lax. The
  # `__Host-` prefix requires the `Secure` attribute and forbids a
  # `Domain` attribute, which in turn requires HTTPS — dev/test serve
  # plain HTTP, so they use a non-`__Host-`, non-`Secure` cookie instead.
  @session_max_age_seconds 30 * 24 * 60 * 60

  @session_options (if Mix.env() == :prod do
                      [
                        store: :cookie,
                        key: "__Host-alplus_session",
                        signing_salt: "nM1ZvG0K",
                        same_site: "Lax",
                        http_only: true,
                        secure: true,
                        max_age: @session_max_age_seconds
                      ]
                    else
                      [
                        store: :cookie,
                        key: "_alplus_key",
                        signing_salt: "nM1ZvG0K",
                        same_site: "Lax",
                        http_only: true,
                        max_age: @session_max_age_seconds
                      ]
                    end)

  # `:peer_data` and `:x_headers` are what the website health check's rate
  # limiter reads: a LiveView socket never runs the plug pipeline, so the
  # visitor IP has to arrive with the connection.
  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :x_headers, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :x_headers, session: @session_options]]

  plug AlplusWeb.Plugs.CloudflareRemoteIp
  plug AlplusWeb.Plugs.LegacyDomainRedirect

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :alplus,
    gzip: not code_reloading?,
    only: AlplusWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug AshPhoenix.Plug.CheckCodegenStatus
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :alplus
  end

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug AlplusWeb.Plugs.RedactedTelemetry, event_prefix: [:phoenix, :endpoint]

  plug AlplusWeb.Plugs.ParseBody,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    body_reader: {AlplusWeb.BodyReader, :read_body, []},
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug AlplusWeb.Router
end
